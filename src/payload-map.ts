/**
 * `payload_map` — the rule-owned declaration that builds a callable's
 * request payload from a source event at fire time. Lives on
 * `job_rule.payload_map` (jsonb); authored `json_schema` validates it at
 * the form/submit boundary; this module is the single shared contract
 * between the form widget, the submit validator and the fire-time
 * interpreter — closed vocabulary, no arbitrary code (same posture as
 * the rule `filter` predicate vocabulary).
 *
 * A rule with an absent/empty map forwards the event payload verbatim —
 * same default as the retired `payload_mode: "verbatim"`.
 *
 * Model (v2):
 *   - every value has a PRIMARY entry plus an optional `fallback` clause
 *     list — the fallback is a property OF the value, never a kind.
 *   - `list` builds `string[]`/`unknown[]` element-by-element, each item
 *     sourced independently.
 *   - `map` builds an object key-by-key (template `variables`).
 *   - `inject` is DECLARATION-ONLY: it materializes via `x_inject` /
 *     `x_semantic` schema annotations — never a user-picked source.
 */

/** Fallback clause — one nesting level, user-sourced kinds only. */
export type PayloadMapFallbackClause =
  | { kind: "const"; value: unknown }
  | { kind: "path"; path: string }
  | { kind: "meta"; meta: PayloadMapMeta };

/** User-authored source for a single scalar value. */
export type PayloadMapLeafEntry =
  | { kind: "const"; value: unknown; fallback?: PayloadMapFallbackClause[] }
  | { kind: "path"; path: string; fallback?: PayloadMapFallbackClause[] }
  | { kind: "meta"; meta: PayloadMapMeta; fallback?: PayloadMapFallbackClause[] };

/** Value allowed inside `list` items / `map` entries — leaf kinds or a
 *  declared injector (the marker lands verbatim and the dispatcher
 *  resolves it per-fire). */
export type PayloadMapItemEntry =
  | PayloadMapLeafEntry
  | { kind: "inject"; inject: PayloadInjector };

/** Where one target field's value comes from. */
export type PayloadMapEntry =
  | PayloadMapLeafEntry
  /** Fire-time injection — declaration-only (`x_inject`/`x_semantic`),
   *  emits an `{$inject:name}` marker resolved per-dispatch. */
  | { kind: "inject"; inject: PayloadInjector; fallback?: PayloadMapFallbackClause[] }
  /** Array field built element-by-element — each item one element;
   *  items resolving to undefined are dropped. */
  | { kind: "list"; items: PayloadMapItemEntry[]; fallback?: PayloadMapFallbackClause[] }
  /** Object field built key-by-key (e.g. template `variables`). */
  | { kind: "map"; entries: Record<string, PayloadMapItemEntry>; fallback?: PayloadMapFallbackClause[] };

export type PayloadMapMeta = "actor_uuid" | "rule_id" | "fired_at" | "actor_locale";

export const PAYLOAD_MAP_META_KINDS: readonly PayloadMapMeta[] = [
  "actor_uuid",
  "rule_id",
  "fired_at",
  "actor_locale",
];

/**
 * Fire-time injector vocabulary — values generated by the DISPATCHER at
 * republish time (never at arm: a scheduled payload would replay the same
 * value every fire otherwise). Declaration-only via `x_inject` /
 * `x_semantic` — not a user-picked source kind.
 *   - `uuid`          — fresh v4 uuid per dispatch (correlation ids)
 *   - `now_iso`       — dispatch instant, ISO 8601
 *   - `now_ms`        — dispatch instant, epoch ms
 *   - `session_actor` — actor uuid riding the forwarded auth headers
 */
export type PayloadInjector = "uuid" | "now_iso" | "now_ms" | "session_actor";

export const PAYLOAD_INJECTORS: readonly PayloadInjector[] = [
  "uuid",
  "now_iso",
  "now_ms",
  "session_actor",
];

/** Marker key emitted by `{kind:"inject"}` at arm time — the dispatcher
 *  replaces single-key `{$inject:name}` objects with the generated value. */
export const PAYLOAD_INJECT_MARK = "$inject";

/** Context the dispatcher reads injector values from. */
export interface PayloadInjectContext {
  /** Actor uuid riding the due message's forwarded auth headers
   *  (`x-user-id`). Absent on the system lane → `session_actor` resolves
   *  to undefined and the field is omitted (no invented identity). */
  session_actor?: string;
}

