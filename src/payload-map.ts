/** target field key → source declaration. `null`/`{}` = verbatim passthrough. */
export type PayloadMap = Record<string, PayloadMapEntry>;

/** Context the resolver reads meta values from. */
export interface PayloadMapContext {
  /** Who armed the rule (stored actor). */
  actor_uuid?: string;
  rule_id?: string;
  /** Fire timestamp (epoch ms) — set by the engine at dispatch. */
  fired_at?: number;
  /** Locale (BCP-47, e.g. `it-IT`) of the actor whose event triggered the
   *  arm — read off the message's auth headers (`x-user-locale`). Absent
   *  on the system lane / anonymous events. */
  actor_locale?: string;
}

/** Minimal JSONPath resolver: `$` = root, `$.a.b.c` = nested lookup. */
export function resolvePath(payload: unknown, path: string): unknown {
  if (path === "$") return payload;
  if (!path.startsWith("$.")) return undefined;
  let cur: unknown = payload;
  for (const seg of path.slice(2).split(".")) {
    if (cur === null || typeof cur !== "object") return undefined;
    cur = (cur as Record<string, unknown>)[seg];
  }
  return cur;
}

/** Resolve a fallback clause (leaf kinds only — never inject). */
function resolveClause(
  clause: PayloadMapFallbackClause,
  eventPayload: unknown,
  ctx: PayloadMapContext,
): unknown {
  switch (clause.kind) {
    case "const":
      return clause.value;
    case "path":
      return resolvePath(eventPayload, clause.path);
    case "meta":
      return ctx[clause.meta];
  }
}

/** "Empty" per the fallback contract — null, undefined, empty string,
 *  empty array, empty object. `0` and `false` are legitimate values. */
function isEmptyValue(v: unknown): boolean {
  if (v === undefined || v === null || v === "") return true;
  if (Array.isArray(v)) return v.length === 0;
  if (typeof v === "object") return Object.keys(v as object).length === 0;
  return false;
}

/** Primary value + declared fallback clauses — first non-empty wins.
 *  A primary/clause resolving to null, undefined, "", [] or {} lets the
 *  next clause try ("se il valore è nullo o vuoto o non definito…"). */
function resolveWithFallback(
  primary: unknown,
  fallback: PayloadMapFallbackClause[] | undefined,
  eventPayload: unknown,
  ctx: PayloadMapContext,
): unknown {
  if (!isEmptyValue(primary)) return primary;
  if (!fallback) return primary;
  for (const clause of fallback) {
    const v = resolveClause(clause, eventPayload, ctx);
    if (!isEmptyValue(v)) return v;
  }
  return primary;
}

function resolveItemEntry(
  entry: PayloadMapItemEntry,
  eventPayload: unknown,
  ctx: PayloadMapContext,
): unknown {
  if (entry.kind === "inject") {
    return { [PAYLOAD_INJECT_MARK]: entry.inject };
  }
  const primary = resolveClause(entry, eventPayload, ctx);
  return resolveWithFallback(primary, entry.fallback, eventPayload, ctx);
}

function resolveEntry(
  entry: PayloadMapEntry,
  eventPayload: unknown,
  ctx: PayloadMapContext,
): unknown {
  switch (entry.kind) {
    case "const":
    case "path":
    case "meta":
      return resolveItemEntry(entry, eventPayload, ctx);
    case "inject":
      return resolveWithFallback(
        { [PAYLOAD_INJECT_MARK]: entry.inject },
        entry.fallback,
        eventPayload,
        ctx,
      );
    case "list": {
      const items = entry.items
        .map((item) => resolveItemEntry(item, eventPayload, ctx))
        .filter((v) => v !== undefined);
      return resolveWithFallback(items, entry.fallback, eventPayload, ctx);
    }
    case "map": {
      const out: Record<string, unknown> = {};
      for (const [k, sub] of Object.entries(entry.entries)) {
        out[k] = resolveItemEntry(sub, eventPayload, ctx);
      }
      return resolveWithFallback(out, entry.fallback, eventPayload, ctx);
    }
  }
}

/**
 * Apply a payload map: for each declared target field, resolve its entry
 * against the source event payload + fire context. `null`/absent map →
 * the event payload verbatim (the default passthrough).
 */
export function applyPayloadMap(
  map: PayloadMap | null | undefined,
  eventPayload: unknown,
  ctx: PayloadMapContext,
): unknown {
  if (!map || Object.keys(map).length === 0) return eventPayload;
  const out: Record<string, unknown> = {};
  for (const [field, entry] of Object.entries(map)) {
    out[field] = resolveEntry(entry, eventPayload, ctx);
  }
  return out;
}

function isInjectMarker(v: unknown): v is { [PAYLOAD_INJECT_MARK]: PayloadInjector } {
  if (v === null || typeof v !== "object" || Array.isArray(v)) return false;
  const keys = Object.keys(v as Record<string, unknown>);
  return keys.length === 1 && keys[0] === PAYLOAD_INJECT_MARK;
}

function injectorValue(name: PayloadInjector, ctx: PayloadInjectContext): unknown {
  switch (name) {
    case "uuid":
      return crypto.randomUUID();
    case "now_iso":
      return new Date().toISOString();
    case "now_ms":
      return Date.now();
    case "session_actor":
      return ctx.session_actor;
  }
}

/**
 * Fire-time pass run by the dispatcher on the armed payload: deep-walks
 * and replaces every `{$inject:name}` marker with a freshly generated
 * value. Unresolvable injectors (`session_actor` with no session) resolve
 * to undefined — the field is omitted, never invented.
 */
export function applyPayloadInjectors(
  payload: unknown,
  ctx: PayloadInjectContext,
): unknown {
  if (isInjectMarker(payload)) {
    return injectorValue(payload[PAYLOAD_INJECT_MARK], ctx);
  }
  if (Array.isArray(payload)) {
    return payload.map((v) => applyPayloadInjectors(v, ctx));
  }
  if (payload !== null && typeof payload === "object") {
    const out: Record<string, unknown> = {};
    for (const [k, v] of Object.entries(payload as Record<string, unknown>)) {
      out[k] = applyPayloadInjectors(v, ctx);
    }
    return out;
  }
  return payload;
}

// ─── Declared seeding — materialization-time derivation ─────────────────

interface JsonSchemaLike {
  type?: string;
  properties?: Record<string, JsonSchemaLike>;
  required?: string[];
  [k: string]: unknown;
}

/** The entry a declared annotation produces for one field, or undefined
 *  when the source side cannot provide it (fail-obvious, never guessed). */
function semanticEntry(
  slot: PayloadSemanticSlot,
  sourceSchema: JsonSchemaLike | undefined,
  sourceEntity: { key: string; entity: string; table: string } | undefined,
): PayloadMapEntry | undefined {
  switch (slot) {
    case "entity.uuid":
    case "entity.id": {
      const leaf = slot === "entity.uuid" ? "uuid" : "id";
      const sub = sourceSchema?.properties?.[sourceEntity?.key ?? ""];
      if (!sourceEntity || !sub?.properties?.[leaf]) return undefined;
      return { kind: "path", path: `$.${sourceEntity.key}.${leaf}` };
    }
    case "entity.table":
      return sourceEntity ? { kind: "const", value: sourceEntity.table } : undefined;
    case "actor.uuid":
      return { kind: "inject", inject: "session_actor" };
  }
}

/**
 * Derive the DECLARED auto-entries for a callable's payload_schema —
 * `x_inject` and `x_semantic` fields materialize `{kind:"inject"}` /
 * the semantic suggestion when (and only when) the map doesn't already
 * declare an entry. Explicitly authored entries ALWAYS win.
 *
 * This is a pure data derivation: callers merge it into the form's
 * initial/baseline data (or the stored map) so machine-written values
 * never masquerade as user edits.
 */
export function seedPayloadMapEntries(
  targetSchema: Record<string, unknown> | undefined,
  sourceSchema: Record<string, unknown> | undefined,
  sourceEntity: { key: string; entity: string; table: string } | undefined,
  map: PayloadMap,
): PayloadMap {
  if (!targetSchema?.properties) return map;
  const next = { ...map };
  for (const [field, prop] of Object.entries(
    targetSchema.properties as Record<string, JsonSchemaLike>,
  )) {
    if (next[field] !== undefined) continue;
    const inject = prop[PAYLOAD_X_INJECT] as PayloadInjector | undefined;
    if (inject && PAYLOAD_INJECTORS.includes(inject)) {
      next[field] = { kind: "inject", inject };
      continue;
    }
    const slot = prop[PAYLOAD_X_SEMANTIC] as PayloadSemanticSlot | undefined;
    if (slot) {
      const entry = semanticEntry(slot, sourceSchema as JsonSchemaLike | undefined, sourceEntity);
      if (entry) next[field] = entry;
    }
  }
  return next;
}
