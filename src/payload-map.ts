/** Field whose value the dispatcher MAY generate — names a
 *  `PayloadInjector`. Seeded automatically; an explicitly authored
 *  entry wins over the declaration. */
export const PAYLOAD_X_INJECT = "x_inject";
/** Private setter — a platform-owned field that MUST NOT render
 *  as a form input (reserved traceability/correlation fields). */
export const PAYLOAD_X_NOT_EDITABLE = "x_not_editable";
/** Semantic derivation slot — declares what context the field wants so
 *  the mapping is a lookup, never a guess. */
export const PAYLOAD_X_SEMANTIC = "x_semantic";
/** Catalog-backed const value — the form renders a ComboSelect fed by
 *  the declared source instead of free text. */
export const PAYLOAD_X_OPTIONS = "x_options";
/** For `kind:"map"` fields — where the suggested entry keys come from:
 *  `{from: <other field>, prop: <row prop>}` reads the selected option's
 *  source row property (e.g. a template's `variables` schema). */
export const PAYLOAD_X_MAP_KEYS = "x_map_keys";

/** Semantic slots — declared on BOTH sides (event emits + callable
 *  schema) so derivation is a lookup, never a guess:
 *   - `entity.uuid`  — uuid of the event's declared entity snapshot
 *   - `entity.id`    — numeric id of the declared entity snapshot
 *   - `entity.table` — table name declared on the emit
 *   - `actor.uuid`   — the session actor riding the event headers
 */
export type PayloadSemanticSlot = "entity.uuid" | "entity.id" | "entity.table" | "actor.uuid";

export const PAYLOAD_SEMANTIC_SLOTS: readonly PayloadSemanticSlot[] = [
  "entity.uuid",
  "entity.id",
  "entity.table",
  "actor.uuid",
];

